"""Regenerate the Engram normalizer's Unicode 16.0.0 tables without changing tokenizer policy."""
import argparse
import re
import subprocess
import sys
import unicodedata as ucd
from pathlib import Path

from unicode_tables import combining_runs, rows

ROOT = Path(__file__).resolve().parents[2]
VERSION = "16.0.0"


def mappings(transform):
    """Sorted mappings into concatenated code-point sequences, including Hangul decomposition."""
    entries, sequences = [], []
    for cp in range(0x110000):
        text = transform(chr(cp))
        if text != chr(cp):
            entries.append((cp, len(sequences), len(text)))
            sequences.extend(map(ord, text))
    return entries, sequences


def render():
    """Emit data only; normalization order and mark removal stay in token_map.zig."""
    if ucd.unidata_version != VERSION:
        raise ValueError(f"Need Unicode {VERSION}, found {ucd.unidata_version}")
    decompositions, sequences = mappings(lambda s: ucd.normalize("NFKD", s))
    lowercases, lower_sequences = mappings(str.lower)
    marks = [cp for cp in range(0x110000) if ucd.category(chr(cp)).startswith("M")]
    cccs = combining_runs(range(0x110000))
    scalar = lambda v: f"0x{v:04X}"
    entry = lambda v: f".{{ .cp = 0x{v[0]:04X}, .start = {v[1]}, .len = {v[2]} }}"
    triple = lambda v: ".{ " + ", ".join(scalar(x) for x in v) + " }"
    out = [
        f"//! Generated by tools/zig/nfkd_tables.py from Unicode {VERSION}; do not edit.",
        "", "pub const Decomp = struct { cp: u21, start: u32, len: u8 };", "",
        "/// All NFKD sequences concatenated, indexed by Decomp.start/.len.",
        "pub const sequences = [_]u21{", *rows(sequences, 8, scalar), "};", "",
        "pub const decompositions = [_]Decomp{", *rows(decompositions, 1, entry), "};", "",
        "/// Sorted Mn/Mc/Me code points; StripAccents removes all category M* characters.",
        "pub const marks = [_]u21{", *rows(marks, 8, scalar), "};", "",
        "pub const Lower = struct { cp: u21, start: u32, len: u8 };", "",
        "/// Full lowercase mappings concatenated (Rust char::to_lowercase semantics).",
        "pub const lower_sequences = [_]u21{", *rows(lower_sequences, 8, scalar), "};", "",
        "pub const lowercases = [_]Lower{", *rows(lowercases, 1, entry), "};", "",
        "/// First, last, canonical combining class for nonzero combining classes.",
        "pub const cccs = [_][3]u21{", *rows(cccs, 4, triple), "};", "",
    ]
    return "\n".join(out)


def tokens(text):
    """Ignore comments and whitespace when checking an existing generated data file."""
    return re.sub(r"\s+", "", re.sub(r"//[^\n]*", "", text))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--zig", default="zig", help="Zig 0.17.0 formatter, used when writing")
    args = parser.parse_args()
    path = ROOT / "zig/src/core/tokenizer/nfkd_data.zig"
    text = render()
    if args.check:
        if tokens(path.read_text()) != tokens(text):
            sys.exit("NFKD table data differs from Unicode 16.0.0")
        print("NFKD_DATA_IDENTICAL Unicode", VERSION)
        return
    version = subprocess.check_output([args.zig, "version"], text=True).strip()
    if version != "0.17.0":
        sys.exit(f"Need Zig 0.17.0, found {version}")
    formatted = subprocess.run([args.zig, "fmt", "--stdin"], input=text, text=True,
                               capture_output=True, check=True).stdout
    path.write_text(formatted)
    print("Wrote", path.relative_to(ROOT))


if __name__ == "__main__":
    main()
