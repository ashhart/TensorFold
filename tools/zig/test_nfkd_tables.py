"""The generated Engram NFKD tables reproduce, and refuse to build on the wrong Unicode."""
import sys
import unittest
from unittest.mock import patch

import nfkd_tables as tables


class GeneratorTests(unittest.TestCase):
    def test_the_committed_table_is_what_the_generator_renders(self):
        if tables.unicodedata.unidata_version != tables.VERSION:
            self.skipTest("this interpreter has Unicode %s" % tables.unicodedata.unidata_version)
        rendered = tables.formatted(tables.render(), tables.ZIG)
        self.assertEqual(tables.OUT.read_text(), rendered,
                         "nfkd_data.zig is stale; rerun tools/zig/nfkd_tables.py --zig zig")

    def test_the_header_names_the_generator_that_is_committed(self):
        head = tables.OUT.read_text().splitlines()[:2]
        self.assertEqual(head, [
            "// Generated by tools/zig/nfkd_tables.py from the Unicode %s character database; do not edit."
            % tables.VERSION,
            'pub const version = "%s";' % tables.VERSION,
        ])
        self.assertTrue((tables.ROOT / "tools" / "zig" / "nfkd_tables.py").is_file())

    def test_the_tables_match_the_pinned_unicode_version(self):
        self.assertEqual(tables.VERSION, "16.0.0")
        if tables.unicodedata.unidata_version != tables.VERSION:
            self.skipTest("this interpreter has Unicode %s" % tables.unicodedata.unidata_version)
        self.assertEqual(tables.unicodedata.unidata_version, tables.VERSION)

    def test_a_wrong_unicode_version_is_refused_rather_than_emitted(self):
        with patch.object(tables.unicodedata, "unidata_version", "15.0.0"):
            with patch.object(sys, "argv", ["nfkd_tables.py", "--check"]):
                with self.assertRaises(SystemExit) as raised:
                    tables.main()
        self.assertIn("need 16.0.0", str(raised.exception.code))

    def test_the_guard_runs_before_the_table_is_written(self):
        before = tables.OUT.read_text()
        with patch.object(tables.unicodedata, "unidata_version", "15.0.0"):
            with patch.object(sys, "argv", ["nfkd_tables.py"]):
                with self.assertRaises(SystemExit):
                    tables.main()
        self.assertEqual(tables.OUT.read_text(), before)


if __name__ == "__main__":
    unittest.main()
