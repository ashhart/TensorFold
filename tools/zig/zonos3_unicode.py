#!/usr/bin/env python3
"""unicode_words.zig for zonos3: Python's word characters, letters and digits, and upper case. Pipe through zig fmt."""

import re
import sys
import unicodedata

WORD = re.compile(r"\w")


def ranges(test):
    out, start = [], None
    for cp in range(0x110000):
        hit = not 0xD800 <= cp < 0xE000 and test(chr(cp))
        if hit and start is None:
            start = cp
        if not hit and start is not None:
            out.append((start, cp - 1))
            start = None
    return out


def packed(numbers, indent="    "):
    lines, line = [], indent
    for n in numbers:
        item = f"0x{n:x}, "
        if len(line) + len(item) > 118:
            lines.append(line.rstrip())
            line = indent
        line += item
    lines.append(line.rstrip())
    return "\n".join(lines)


def main():
    word = ranges(lambda c: WORD.match(c) is not None)
    wordy = ranges(lambda c: unicodedata.category(c)[0] in "LN")
    single, multi = [], []
    for cp in range(0x110000):
        if 0xD800 <= cp < 0xE000:
            continue
        up = chr(cp).upper()
        if up == chr(cp):
            continue
        if len(up) == 1:
            single += [cp, ord(up)]
        else:
            multi.append((cp, [ord(c) for c in up]))
    out = [
        "//! Generated by tools/zig/zonos3_unicode.py: Python's `\\w` and `str.upper` (Unicode "
        + unicodedata.unidata_version + "), for the edit tokens.",
        "",
        "/// Inclusive code point ranges `\\w` matches, ascending: first, last, first, last, ...",
        "pub const word = [_]u32{",
        packed([n for pair in word for n in pair]),
        "};",
        "",
        "/// Inclusive ranges of the letters and digits (categories L* and N*): what the aligner calls a word.",
        "pub const wordy = [_]u32{",
        packed([n for pair in wordy for n in pair]),
        "};",
        "",
        "/// Code points whose upper case is one other code point, ascending: from, to, from, to, ...",
        "pub const upper = [_]u32{",
        packed(single),
        "};",
        "",
        "/// Code points whose upper case is several: from, count, then the code points.",
        "pub const upper_many = [_]u32{",
        packed([n for cp, ups in multi for n in (cp, len(ups), *ups)]),
        "};",
        "",
    ]
    sys.stdout.write("\n".join(out))


if __name__ == "__main__":
    main()
