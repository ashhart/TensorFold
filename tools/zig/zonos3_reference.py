#!/usr/bin/env python3
"""Reference dumps for the ZONOS3 Mini port from the publisher's PyTorch code: what zonos3-generate checks against."""

USAGE = """Run inside an environment that has the publisher's `zonos3` package (github.com/Zyphra/ZONOS3-Mini, `pip install -e
model`) and a local snapshot of huggingface.co/Zyphra/ZONOS3-Mini; docs/recipes/zonos3-mini.md pins both and gives
the commands. Every subcommand writes float32 / int32 .npy files under OUT, named as zonos3-generate reads them.

    requests RELEASE OUT            eight GenerateRequest files (two voice paths, sampled and greedy; conditions; guidance)
    rows     LM_DIR REQUEST OUT     one request generated by zonos3.reference: prompt rows, frames, audio
    codec    CODES.npy OUT          the codec decoder (CPU fp32) on codes [frames, 10], with its capture points
    encoder  GENERATOR AUDIO.npy OUT   the codec encoder's acoustic branch in fp32 on one lane of 44.1 kHz audio
    teacher  TEACHER_DIR FEATS.npy OUT the SSL teacher in fp32 on one lane's feature rows
    quantize GENERATOR ACOUSTIC.npy SSL.npy OUT  the quantizer in fp32 on those two runs' rows: the lane's codes
    clip     GENERATOR TEACHER_DIR AUDIO.npy OUT [--seconds S]  a whole clip's codes in fp32, lane by lane

The backbone's per-layer dump and the encoder's bf16 production dump come from the publisher's tool unchanged:
    tools/dump_golden.py lm LM_DIR --input-ids OUT/input_ids.npy --dtype f32 --mode full -o DIR
    tools/dump_golden.py codec-encoder --generator GENERATOR --audio CLIP -o DIR
The release runs its encoder and teacher under bf16 autocast on CUDA; `encoder` and `teacher` here run the same
modules and weights in fp32, the precision the port computes in.
"""

import argparse
import base64
import json
from pathlib import Path

import numpy as np
import torch

CODEC = "opus_dual_3n_600k_sched600k_r4096_step600000"
TEXT = "The quick brown fox jumps over the lazy dog, and then it rests by the river."
VOICE = "gguf/voices/English/Savannah_en-American_F_1"


def save(out, taps):
    for name, value in taps.items():
        np.save(out / f"{name}.npy", np.ascontiguousarray(value, dtype=np.float32))


def requests(args):
    """The checks' requests: a voice by embedding and by codes, sampled and greedy, then conditions and guidance."""
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    voice = Path(args.release) / VOICE
    emb = base64.b64encode(Path(f"{voice}.embedding.npy").read_bytes()).decode()
    codes = np.load(f"{voice}.codes.npy").tolist()
    base = {"text": TEXT, "language": "en_us", "seed": 42, "stream": False}
    by_embedding = {**base, "speaker_mode": "embedding", "speaker_embedding_base64": emb}
    by_reference = {**base, "speaker_reference_codes": codes}
    for name, request in (("embedding", by_embedding), ("reference", by_reference)):
        (out / f"{name}.json").write_text(json.dumps(request))
        (out / f"greedy_{name}.json").write_text(json.dumps({**request, "temperature": 0.0}))
    # speaker guidance on each voice path, condition rows by raw value and by bucket, and both together
    greedy = {**by_reference, "temperature": 0.0}
    values = {"condition_values": {"loudness": -20.0, "speaking_rate": 18.0}}
    more = {
        "guided_reference": {**greedy, "speaker_cfg_scale": 1.5},
        "guided_embedding": {**by_embedding, "temperature": 0.0, "speaker_cfg_scale": 1.5},
        "conditions": {**greedy, **values},
        "guided_conditions": {**greedy, "speaker_cfg_scale": 2.0, "condition_buckets": [3, 10, 25]},
    }
    for name, request in more.items():
        (out / f"{name}.json").write_text(json.dumps(request))
    print(f"{4 + len(more)} requests -> {out}")


def rows(args):
    """zonos3.reference's generation of one request: input_ids.npy (+ .cond.json), rows.npy, audio.f32, meta.json."""
    from zonos3.reference.lm import Zonos3LM
    from zonos3.reference.synth import ReferenceAssets, plan_prompt, synthesize

    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    request = json.loads(Path(args.request).read_text())
    device = torch.device(args.device)
    dtype = torch.float32 if args.dtype == "f32" else torch.bfloat16
    lm = Zonos3LM.load(args.lm, device=device, dtype=dtype)
    assets = ReferenceAssets.load()
    plan = plan_prompt(lm, request, assets=assets, device=device)
    np.save(out / "input_ids.npy", plan.cond.input_ids.to(torch.float32).numpy())
    (out / "input_ids.cond.json").write_text(json.dumps(plan.cond_json()) + "\n")
    if plan.twin is not None:  # the guidance twin: its own rows and conditioning, and the scale that mixes the two
        np.save(out / "twin_ids.npy", plan.twin.input_ids.to(torch.float32).numpy())
        (out / "twin_ids.cond.json").write_text(json.dumps({**plan.cond_json(plan.twin), "cfg_scale": plan.cfg_scale}) + "\n")
    result = synthesize(lm, request, assets=assets, device=device, dtype=dtype)
    generated = torch.stack([r.to(torch.int32) for r in result.rows]).numpy()
    np.save(out / "rows.npy", generated)
    result.pcm.astype("<f4").tofile(out / "audio.f32")
    meta = {"seed": result.seed, "eos_frame": result.eos_frame, "frames": len(generated), "samples": len(result.pcm)}
    (out / "meta.json").write_text(json.dumps({**meta, "device": args.device, "dtype": args.dtype}) + "\n")
    print(f"{len(generated)} rows, eos frame {result.eos_frame}, {len(result.pcm) / 44100:.2f} s -> {out}")


def codec(args):
    """The decoder on codes [frames, 10]: latent, stage_{0..8}, trunk, y0 / y1, s0 / s1, mixer, audio."""
    from zonos3.tokenizer import matched_codec

    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    codes = np.load(args.codes).astype(np.int64)
    np.save(out / "codes.npy", codes.astype(np.int32))
    model = matched_codec.load_model(CODEC, "cpu", decoder=args.decoder)
    taps = {}

    def rows_of(name):
        return lambda m, i, o: taps.__setitem__(name, o[0].float().T.contiguous().numpy())

    for i in (0, 2, 4, 6, 8):
        model.stages[i].register_forward_hook(rows_of(f"stage_{i}"))
    model.head.norm.register_forward_hook(lambda m, i, o: taps.__setitem__("trunk", o[0].float().numpy()))
    for i, linear in enumerate(model.head.outs):
        linear.register_forward_hook(lambda m, inp, o, i=i: taps.__setitem__(f"y{i}", o[0].float().numpy()))

    def branches(m, inp):
        for i in range(inp[0].shape[1]):
            taps[f"s{i}"] = inp[0][0, i].float().numpy()

    model.head.mixer.register_forward_pre_hook(branches)
    model.head.mixer.register_forward_hook(lambda m, i, o: taps.__setitem__("mixer", o[0, 0].float().numpy()))
    packed = torch.from_numpy(codes).unsqueeze(0).permute(0, 2, 1)
    with torch.inference_mode():
        taps["latent"] = model.latent(packed)[0].float().T.contiguous().numpy()
        taps["audio"] = model(packed).float().reshape(-1).numpy()
    save(out, taps)
    print(f"{len(codes)} frames, {len(taps)} captures -> {out}")


def encoder(args):
    """The acoustic branch in fp32: internal_audio, lane.0.enc.*, lane.0.stage.N(.in|.lK), lane.0.acoustic."""
    from torch.nn import functional as F

    from zonos3.codec.hybrid10_dual_encoding.model import MossCodec
    from zonos3.codec.resample_exact import resample_exact

    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    state = torch.load(args.generator, map_location="cpu", mmap=True, weights_only=True)
    model = MossCodec(state["config"]["model"])
    model.load_state_dict(state["generator"], strict=True, assign=True)
    model.eval().requires_grad_(False)
    audio = np.load(args.audio).astype(np.float32).reshape(-1)[: 300 * 2940]
    np.save(out / "audio.npy", audio)
    wave = torch.from_numpy(audio)[None, None]
    frames = (wave.shape[-1] + 2939) // 2940
    internal = resample_exact(wave, model.to_internal)
    internal = F.pad(internal, (0, frames * 2944 - internal.shape[-1]))
    enc = model.encoder.cuda().float()
    taps = {}

    def channels_first(name):
        return lambda m, i, o: taps.__setitem__(name, o[0].float().T.contiguous().cpu().numpy())

    enc[0].register_forward_hook(channels_first("lane.0.enc.in"))
    for b in (0, 1):
        block = enc[1 + b].module.block
        for u in range(3):
            block[u].register_forward_hook(channels_first(f"lane.0.enc.b{b}.res{u}"))
        enc[1 + b].register_forward_hook(channels_first(f"lane.0.enc.b{b}.conv"))
    for si, index in enumerate((4, 6, 8, 10, 12)):
        enc[index].register_forward_hook(channels_first(f"lane.0.stage.{si}"))
        enc[index].input_proj.register_forward_hook(
            lambda m, i, o, si=si: taps.__setitem__(f"lane.0.stage.{si}.in", o[0].float().contiguous().cpu().numpy())
        )
        for li, layer in enumerate(enc[index].layers):
            # an eval stage calls layer.forward itself, past any hook
            def forward(x, inner=layer.forward, name=f"lane.0.stage.{si}.l{li}"):
                o = inner(x)
                taps[name] = o[0].float().contiguous().cpu().numpy()
                return o

            layer.forward = forward
    torch.backends.cuda.matmul.allow_tf32 = False
    torch.backends.cudnn.allow_tf32 = False
    with torch.inference_mode():
        latent = enc(internal.cuda())
    taps["lane.0.acoustic"] = latent[0].float().T.contiguous().cpu().numpy()
    taps["internal_audio"] = internal[0].T.contiguous().numpy()
    save(out, taps)
    print(f"{frames} frames, {len(taps)} captures -> {out}")


def teacher(args):
    """The teacher in fp32 on feature rows [rows, 160]: .feature_projection, .layer.N, and lane.0.ssl (layer 16)."""
    from zonos3.codec.s1dac.losses import SemanticTeacher

    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    feats = np.load(args.features).astype(np.float32)
    model = SemanticTeacher(args.teacher, layer=16, dtype=torch.float32).cuda().eval()
    taps = {"lane.0.ssl.features": feats}
    inner = model.model
    inner.feature_projection.register_forward_hook(
        lambda m, i, o: taps.__setitem__("lane.0.ssl.feature_projection", o[0][0].float().cpu().numpy())
    )
    for li, layer in enumerate(inner.encoder.layers):
        layer.register_forward_hook(
            lambda m, i, o, li=li: taps.__setitem__(f"lane.0.ssl.layer.{li}", o[0][0].float().cpu().numpy())
        )
    torch.backends.cuda.matmul.allow_tf32 = False
    with torch.inference_mode():
        x = torch.from_numpy(feats)[None].cuda()
        mask = torch.ones(1, x.shape[1], dtype=torch.bool, device="cuda")
        taps["lane.0.ssl"] = model(x, mask)[0].float().cpu().numpy()
    save(out, taps)
    print(f"{len(feats)} rows, {len(taps)} captures -> {out}")


def quantize(args):
    """The quantizer in fp32 on one lane's acoustic and teacher rows: pooled, semantic, rvq.N.*, codes."""
    from zonos3.codec.hybrid10_dual_encoding.model import MossCodec
    from zonos3.codec.s1dac.losses import average_ssl_frames

    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    state = torch.load(args.generator, map_location="cpu", mmap=True, weights_only=True)
    cfg = state["config"]["model"]
    model = MossCodec(cfg)
    model.load_state_dict(state["generator"], strict=True, assign=True)
    model.eval().requires_grad_(False).float()
    acoustic = torch.from_numpy(np.load(args.acoustic).astype(np.float32)).T[None]  # [1, 1024, frames]
    ssl = torch.from_numpy(np.load(args.ssl).astype(np.float32))[None]  # [1, rows, 1024]
    frames = acoustic.shape[-1]
    taps = {}

    def rows_of(name, value):
        taps[name] = value[0].float().T.contiguous().numpy()

    with torch.inference_mode():
        # the teacher saw a full 20 s lane: its rows pool onto the lane's 300 frames, of which the clip has `frames`
        pooled = average_ssl_frames(ssl, 300, cfg["dual_encoding"]["window_ratio"])[..., :frames]
        rows_of("lane.0.pooled", pooled)
        semantic = model.semantic_encoder(pooled)
        rows_of("lane.0.semantic", semantic)
        q1, c1, e1, _, _ = model.quantizer.semantic_quantizer(semantic)
        rows_of("lane.0.rvq.0.projected", e1)
        rows_of("lane.0.rvq.0.quantized", q1)
        prediction = model.semantic_head(q1)
        rows_of("lane.0.semantic_prediction", prediction)
        residual = acoustic - prediction
        rows_of("lane.0.residual", residual)
        codes = [c1[0, 0]]
        for i, quantizer in enumerate(model.quantizer.quantizer.quantizers, 1):
            z_q, _, _, indices, z_e = quantizer(residual)
            rows_of(f"lane.0.rvq.{i}.projected", z_e)
            rows_of(f"lane.0.rvq.{i}.quantized", z_q)
            residual = residual - z_q
            codes.append(indices[0])
    np.save(out / "codes.npy", torch.stack(codes, 1).numpy().astype(np.int32))
    save(out, taps)
    print(f"{frames} frames, {len(taps)} captures -> {out}")


def clip(args):
    """A whole clip encoded in fp32 with the publisher's lanes (20 s, 10 s of left context): audio.npy and codes.npy."""
    from torch.nn import functional as F

    from zonos3.codec.hybrid10_dual_encoding.model import MossCodec
    from zonos3.codec.resample_exact import resample_exact
    from zonos3.codec.s1dac.losses import SemanticTeacher, average_ssl_frames
    from zonos3.codec.s1dac.same_data.npy_ogg_dataset import Wav2Vec2BertFeaturePreprocessor

    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    state = torch.load(args.generator, map_location="cpu", mmap=True, weights_only=True)
    cfg = state["config"]["model"]
    model = MossCodec(cfg)
    model.load_state_dict(state["generator"], strict=True, assign=True)
    model.eval().requires_grad_(False).float().cuda()
    teacher = SemanticTeacher(args.teacher, layer=16, dtype=torch.float32).cuda().eval()
    audio = np.load(args.audio).astype(np.float32).reshape(-1)
    if args.seconds:
        count = int(args.seconds * 44100)
        audio = np.tile(audio, (count + audio.size - 1) // audio.size)[:count].copy()
    audio = audio[: 900 * 2940]
    np.save(out / "audio.npy", audio)
    wave = torch.from_numpy(audio)[None, None]
    frames = (wave.shape[-1] + 2939) // 2940
    internal = resample_exact(wave, model.to_internal.cpu())
    internal = F.pad(internal, (0, frames * 2944 - internal.shape[-1]))
    external = F.pad(wave, (0, frames * 2940 - wave.shape[-1]))
    features = Wav2Vec2BertFeaturePreprocessor(44100)
    torch.backends.cuda.matmul.allow_tf32 = False
    torch.backends.cudnn.allow_tf32 = False
    codes = np.zeros((frames, 10), dtype=np.int32)
    start = 0
    with torch.inference_mode():
        while start < frames:
            # the first lane starts the clip; a later one carries 150 frames of what came before
            context = 0 if start == 0 else 150
            end = min(frames, start + 300 - context)
            first, n = start - context, end - (start - context)
            latent = model.encoder(internal[..., first * 2944 : end * 2944].cuda())
            lane = F.pad(external[0, :, first * 2940 : end * 2940], (0, (300 - n) * 2940))
            info = {}
            features(lane, info)
            feats = info["w2v_bert_input_features"][None].cuda()
            ssl = teacher(feats, torch.ones(1, feats.shape[1], dtype=torch.bool, device="cuda"))
            pooled = average_ssl_frames(ssl, 300, cfg["dual_encoding"]["window_ratio"])[..., :n]
            q1, c1, _, _, _ = model.quantizer.semantic_quantizer(model.semantic_encoder(pooled))
            residual = latent - model.semantic_head(q1)
            lane_codes = [c1[0, 0]]
            for quantizer in model.quantizer.quantizer.quantizers:
                z_q, _, _, indices, _ = quantizer(residual)
                residual = residual - z_q
                lane_codes.append(indices[0])
            codes[start:end] = torch.stack(lane_codes, 1)[context:].cpu().numpy()
            start = end
    np.save(out / "codes.npy", codes)
    print(f"{frames} frames -> {out}")


def main():
    parser = argparse.ArgumentParser(description=__doc__, epilog=USAGE, formatter_class=argparse.RawDescriptionHelpFormatter)
    commands = parser.add_subparsers(dest="command", required=True)
    p = commands.add_parser("requests")
    p.add_argument("release")
    p.add_argument("out")
    p.set_defaults(run=requests)
    p = commands.add_parser("rows")
    p.add_argument("lm")
    p.add_argument("request")
    p.add_argument("out")
    p.add_argument("--device", default="cpu")
    p.add_argument("--dtype", choices=("f32", "bf16"), default="f32")
    p.set_defaults(run=rows)
    p = commands.add_parser("codec")
    p.add_argument("codes")
    p.add_argument("out")
    p.add_argument("--decoder", default="keep2_plain")
    p.set_defaults(run=codec)
    p = commands.add_parser("encoder")
    p.add_argument("generator")
    p.add_argument("audio")
    p.add_argument("out")
    p.set_defaults(run=encoder)
    p = commands.add_parser("teacher")
    p.add_argument("teacher")
    p.add_argument("features")
    p.add_argument("out")
    p.set_defaults(run=teacher)
    p = commands.add_parser("quantize")
    p.add_argument("generator")
    p.add_argument("acoustic")
    p.add_argument("ssl")
    p.add_argument("out")
    p.set_defaults(run=quantize)
    p = commands.add_parser("clip")
    p.add_argument("generator")
    p.add_argument("teacher")
    p.add_argument("audio")
    p.add_argument("out")
    p.add_argument("--seconds", type=float, help="repeat the audio to this length")
    p.set_defaults(run=clip)
    args = parser.parse_args()
    args.run(args)


if __name__ == "__main__":
    main()
