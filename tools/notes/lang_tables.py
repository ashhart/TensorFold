"""Emit zig/src/server/notes/lang_tables.zig from CPython 3.12.8 / Unicode 15.0.0.

Brute-forces every code point for re's \\w, \\s, \\d and for re.I of each letter
that appears in the ML-1 DE/FI cues (lang_cues.py). Exact by construction:
ẞ/ß, ſ, the Kelvin sign, İ/ı, Ä/Ö/Ü.

  PYTHONHASHSEED=0 python -s -P tools/notes/lang_tables.py
  PYTHONHASHSEED=0 python -s -P tools/notes/lang_tables.py --check
"""
from __future__ import annotations

import hashlib
import os
import re
import sys
import tempfile
import unicodedata

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
OUT = os.path.join(ROOT, "zig", "src", "server", "notes", "lang_tables.zig")
NCP = 0x110000


def require_unicode():
    ver = unicodedata.unidata_version
    if ver != "15.0.0":
        sys.stderr.write(f"lang_tables.py needs unicodedata 15.0.0, got {ver}\n")
        sys.exit(2)


def ranges_of(pred):
    out = []
    i = 0
    while i < NCP:
        try:
            ch = chr(i)
        except ValueError:
            i += 1
            continue
        if not pred(ch):
            i += 1
            continue
        j = i
        while j + 1 < NCP:
            try:
                nxt = chr(j + 1)
            except ValueError:
                break
            if not pred(nxt):
                break
            j += 1
        out.append((i, j))
        i = j + 1
    return out


def cue_letters():
    sys.path.insert(0, HERE)
    import lang_cues  # noqa: E402

    letters = set()
    for pat in (lang_cues.DE_PAST_CUE.pattern, lang_cues.FI_PAST_CUE.pattern, lang_cues.FI_CLIT):
        for ch in pat:
            if ch.isalpha():
                letters.add(ch)
    return lang_cues, sorted(letters, key=lambda c: (ord(c), c))


def letter_matches(letter: str):
    rx = re.compile("^" + re.escape(letter) + "$", re.I)
    hits = []
    for i in range(NCP):
        try:
            ch = chr(i)
        except ValueError:
            continue
        if rx.match(ch):
            hits.append(i)
    return hits


def zig_ranges(name, ranges):
    lines = [f"pub const {name} = [_][2]u21{{"]
    for lo, hi in ranges:
        lines.append(f"    .{{ 0x{lo:X}, 0x{hi:X} }},")
    lines.append("};")
    return "\n".join(lines)


def zig_cps(name, cps):
    lines = [f"pub const {name} = [_]u21{{"]
    row = []
    for cp in cps:
        row.append(f"0x{cp:X}")
        if len(row) == 8:
            lines.append("    " + ", ".join(row) + ",")
            row = []
    if row:
        lines.append("    " + ", ".join(row) + ",")
    lines.append("};")
    return "\n".join(lines)


def ident(letter: str):
    return f"u{ord(letter):04X}"


def render(lang_cues, letters, word, space, digit, folds):
    de_h = hashlib.sha256(lang_cues.DE_PAST_CUE.pattern.encode()).hexdigest()
    fi_h = hashlib.sha256(lang_cues.FI_PAST_CUE.pattern.encode()).hexdigest()
    py = sys.version.split()[0]
    uni = unicodedata.unidata_version
    parts = [
        "//! Generated by tools/notes/lang_tables.py. Do not edit.",
        f"//! Python {py}, Unicode {uni}.",
        f"//! DE_PAST_CUE sha256={de_h}",
        f"//! FI_PAST_CUE sha256={fi_h}",
        "",
        "fn inRanges(ranges: []const [2]u21, cp: u21) bool {",
        "    var lo: usize = 0;",
        "    var hi: usize = ranges.len;",
        "    while (lo < hi) {",
        "        const mid = lo + (hi - lo) / 2;",
        "        const r = ranges[mid];",
        "        if (cp < r[0]) hi = mid else if (cp > r[1]) lo = mid + 1 else return true;",
        "    }",
        "    return false;",
        "}",
        "",
        "fn inCps(cps: []const u21, cp: u21) bool {",
        "    var lo: usize = 0;",
        "    var hi: usize = cps.len;",
        "    while (lo < hi) {",
        "        const mid = lo + (hi - lo) / 2;",
        "        const v = cps[mid];",
        "        if (cp == v) return true;",
        "        if (cp < v) hi = mid else lo = mid + 1;",
        "    }",
        "    return false;",
        "}",
        "",
        zig_ranges("word_ranges", word),
        "",
        zig_ranges("space_ranges", space),
        "",
        zig_ranges("digit_ranges", digit),
        "",
        "pub fn isWord(cp: u21) bool {",
        "    return inRanges(&word_ranges, cp);",
        "}",
        "",
        "pub fn isSpace(cp: u21) bool {",
        "    return inRanges(&space_ranges, cp);",
        "}",
        "",
        "pub fn isDigit(cp: u21) bool {",
        "    return inRanges(&digit_ranges, cp);",
        "}",
        "",
    ]
    for letter in letters:
        parts.append(zig_cps(f"fold_{ident(letter)}", folds[letter]))
        parts.append("")
    parts.append("/// re.I match of `want` (a cue letter) against code point `cp`.")
    parts.append("pub fn letterEq(cp: u21, want: u21) bool {")
    parts.append("    return switch (want) {")
    for letter in letters:
        w = ord(letter)
        parts.append(f"        0x{w:X} => inCps(&fold_{ident(letter)}, cp),")
    parts.append("        else => cp == want,")
    parts.append("    };")
    parts.append("}")
    parts.append("")
    return "\n".join(parts)


def generate():
    require_unicode()
    lang_cues, letters = cue_letters()
    word_rx = re.compile(r"\w", re.UNICODE)
    space_rx = re.compile(r"\s", re.UNICODE)
    digit_rx = re.compile(r"\d", re.UNICODE)
    word = ranges_of(lambda ch: word_rx.match(ch) is not None)
    space = ranges_of(lambda ch: space_rx.match(ch) is not None)
    digit = ranges_of(lambda ch: digit_rx.match(ch) is not None)
    folds = {letter: letter_matches(letter) for letter in letters}
    return render(lang_cues, letters, word, space, digit, folds)


def main():
    text = generate()
    check = "--check" in sys.argv[1:]
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    if check:
        if not os.path.isfile(OUT):
            sys.stderr.write(f"missing {OUT}\n")
            return 1
        old = open(OUT).read()
        if old != text:
            sys.stderr.write("lang_tables.zig is stale; rerun tools/notes/lang_tables.py\n")
            return 1
        print("lang_tables.zig matches")
        return 0
    tmp = tempfile.NamedTemporaryFile("w", delete=False, dir=os.path.dirname(OUT), encoding="utf-8")
    try:
        tmp.write(text)
        tmp.close()
        os.replace(tmp.name, OUT)
    except Exception:
        try:
            os.unlink(tmp.name)
        except OSError:
            pass
        raise
    print(f"wrote {OUT} ({len(text)} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
