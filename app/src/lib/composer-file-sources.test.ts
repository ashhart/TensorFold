import assert from 'node:assert/strict'
import { composerFileSources, forgetComposerFileSources, makeComposerFileSourcesIncognito } from './composer-file-sources'

const normal = 'synthetic-normal-draft', privateScope = 'synthetic-private-draft', unrelated = 'synthetic-other-draft'
const firstFile = new File(['Synthetic file'], 'first.txt', { type: 'text/plain' })
const privateFile = new File(['Synthetic private file'], 'private.txt', { type: 'text/plain' })
const unrelatedFile = new File(['Synthetic other file'], 'other.txt', { type: 'text/plain' })
const originalOwner = composerFileSources(normal)
originalOwner.set('first', firstFile)
composerFileSources(privateScope).set('private', privateFile)
composerFileSources(unrelated).set('other', unrelatedFile)
makeComposerFileSourcesIncognito(normal, privateScope)
assert.notEqual(composerFileSources(normal), originalOwner, 'Normal-scope callbacks lose their source-map identity after privacy selection')
assert.equal(composerFileSources(normal).size, 0)
assert.equal(originalOwner.size, 0, 'Retired source maps release raw File handles')
assert.equal(composerFileSources(privateScope).get('first'), firstFile, 'Ready original files remain extractable within the private session')
assert.equal(composerFileSources(privateScope).get('private'), privateFile, 'Existing private handles are preserved')
assert.equal(composerFileSources(unrelated).get('other'), unrelatedFile)
const privateOwner = composerFileSources(privateScope)
forgetComposerFileSources(privateScope)
assert.equal(privateOwner.size, 0, 'Explicit Forget releases handles held by older callbacks')
assert.notEqual(composerFileSources(privateScope), privateOwner)
assert.equal(composerFileSources(unrelated).get('other'), unrelatedFile, 'Scoped Forget leaves another draft alone')
const unrelatedOwner = composerFileSources(unrelated)
forgetComposerFileSources()
assert.equal(unrelatedOwner.size, 0)
assert.notEqual(composerFileSources(unrelated), unrelatedOwner, 'Global Forget invalidates every old source-map owner')
forgetComposerFileSources()
console.log('Private file-handle transfer, stale callback ownership, unrelated drafts and scoped/global Forget passed')
