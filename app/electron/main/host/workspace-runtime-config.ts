import { resolveWorkspaceCwd } from './workspace'
import type { WorkspaceRuntimeIpcDeps } from './workspace-runtime-ipc'

// The deps object mirrors the relaxed WorkspaceRuntimeIpcDeps shape (`[key: string]: any`),
// so every one-liner symbol the inline config passed through is forwarded verbatim. The few
// entries the inline version computed from collaborators are typed explicitly so the factory
// can build them here.
export interface WorkspaceRuntimeConfigDeps extends Omit<WorkspaceRuntimeIpcDeps, 'spine' | 'stopLoopsForArchive' | 'validateProjectCwd' | 'publishRemote' | 'isTicketStarting' | 'abortMissionsForArchive'> {
  // Forward-declared / late-bound collaborators — passed as accessors so the config is built
  // before they are assigned while lookups stay lazy.
  spineHost(): unknown
  remoteServer(): { publish(event: { kind: string; data: unknown }): void }
  loopHost: { stopLoopsForArchive(kind: 'project' | 'thread' | 'room' | 'ticket', id: string): Promise<unknown> }
  ticketWorkerRuntime: { isTicketStarting(ticketId: string): boolean }
  abortMissionsForArchive: WorkspaceRuntimeIpcDeps['abortMissionsForArchive']
  [key: string]: any
}

/**
 * Builds the `WorkspaceRuntimeIpcDeps` config consumed by `createWorkspaceRuntimeIpc`.
 *
 * Pure relocation of the ~99-line inline blob from main-app.ts. Every referenced symbol is
 * passed in the deps object and forwarded verbatim; the four computed entries (spine accessor,
 * loopHost stop wrapper, project-cwd validation, remote publish forwarder, ticket-starting
 * probe) are assembled here from the same collaborators the inline closures used.
 */
export function buildWorkspaceRuntimeIpcConfig(deps: WorkspaceRuntimeConfigDeps): WorkspaceRuntimeIpcDeps {
  const {
    fs,
    path,
    randomUUID,
    store,
    handle,
    spineHost,
    isActive,
    archiveEntity,
    killProjectTerminals,
    abortMissionsForArchive,
    loopHost,
    workspaceMutationGuard,
    requireSecurityRole,
    auditEvent,
    auditPreview,
    persistProjects,
    persistThreads,
    persistRooms,
    persistTickets,
    persistSubAgents,
    persistSkills,
    persistProjectMemory,
    persistProjectMemoryCandidates,
    aborters,
    roomAborters,
    DEFAULT_ROOM_COLLABORATION_MODE,
    DEFAULT_ROOM_WORKER_BUDGET,
    ensureRoomWorktree,
    emitRoom,
    emitTicket,
    emitJob,
    remoteServer,
    activeJob,
    patchRoomSupervisorJob,
    finishRoomSupervisorMission,
    finishJob,
    parkRoomIfWorkRemains,
    ensureRoomSupervisorMission,
    roomWorkerBudget,
    claimJob,
    patchJob,
    buildRoomSupervisorJobMetadata,
    ticketsForRoom,
    runtimeProvider,
    inferSeatLane,
    appendRoomSupervisorEvent,
    ticketNeedsReviewAfterBuilder,
    roomTicketConflictBlockers,
    summarizeRoomLeftToWork,
    describeTicketForRoom,
    mkTicket,
    assertTicketRelations,
    normalizeTicketCapabilities,
    normalizeStringList,
    ticketEvidenceFromArgs,
    ticketFileRefs,
    startTicketWork,
    createSubAgentFromLaunch,
    parentForRoomSeat,
    startSubAgent,
    runReadOnlySubAgent,
    executeTool,
    modelRouter,
    modelRouteAutoFailoverEnabled,
    effectiveContextLimit,
    roomContextLimit,
    auditScopedModelRoute,
    runtimeProviderWithFreshModels,
    assertProviderEndpoint,
    modelRouteFailoverText,
    roomRouteHandoff,
    modelRouteResetPolicy,
    roomFinalGateBlockers,
    runRoom,
    normalizeTicketExecution,
    ticketWorkOptionsWithProjectRoute,
    ticketWorkerRuntime,
    resolveProjectProvider,
    ensureTensorFoldStudioStylePrompt,
    streamChat,
    parseJsonLoose,
    createProjectMemoryCandidate,
    approveProjectMemoryCandidate,
    rejectProjectMemoryCandidate,
    projectMemoryCandidateDiff,
    rollbackProjectMemoryEntry,
    forgetProjectMemoryEntry,
    scopeProjectMemoryEntries,
    scopeProjectMemoryCandidates,
    registerWebhookIpc,
    webhookServer,
    rememberConnectorEvents,
    confirmSensitiveAction,
  } = deps

  return {
    fs,
    path,
    randomUUID,
    store,
    handle,
    spine: () => spineHost(),
    isActive,
    archiveEntity,
    killProjectTerminals,
    abortMissionsForArchive,
    stopLoopsForArchive: (kind: Parameters<typeof loopHost.stopLoopsForArchive>[0], id: string) => loopHost.stopLoopsForArchive(kind, id),
    workspaceMutationGuard,
    requireSecurityRole,
    auditEvent,
    auditPreview,
    // Validate a model/user-supplied project cwd the same way workspace tools do:
    // must exist, be a directory, and not be the user's home folder (symlink-resolved).
    // Guards projects:create (incl. the create_project app-control tool) so a model
    // can't point a project — which writes AGENTS.md/CLAUDE.md into its cwd — at $HOME.
    validateProjectCwd: (cwd: string) => resolveWorkspaceCwd(cwd, 'project folder'),
    persistProjects,
    persistThreads,
    persistRooms,
    persistTickets,
    persistSubAgents,
    persistSkills,
    persistProjectMemory,
    persistProjectMemoryCandidates,
    aborters,
    roomAborters,
    DEFAULT_ROOM_COLLABORATION_MODE,
    DEFAULT_ROOM_WORKER_BUDGET,
    ensureRoomWorktree,
    emitRoom,
    emitTicket,
    emitJob,
    publishRemote: (event: { kind: string; data: unknown }) => remoteServer().publish(event),
    activeJob,
    patchRoomSupervisorJob,
    finishRoomSupervisorMission,
    finishJob,
    parkRoomIfWorkRemains,
    ensureRoomSupervisorMission,
    roomWorkerBudget,
    claimJob,
    patchJob,
    buildRoomSupervisorJobMetadata,
    ticketsForRoom,
    runtimeProvider,
    inferSeatLane,
    appendRoomSupervisorEvent,
    ticketNeedsReviewAfterBuilder,
    roomTicketConflictBlockers,
    summarizeRoomLeftToWork,
    describeTicketForRoom,
    mkTicket,
    assertTicketRelations,
    normalizeTicketCapabilities,
    normalizeStringList,
    ticketEvidenceFromArgs,
    ticketFileRefs,
    startTicketWork,
    createSubAgentFromLaunch,
    parentForRoomSeat,
    startSubAgent,
    runReadOnlySubAgent,
    executeTool,
    modelRouter,
    modelRouteAutoFailoverEnabled,
    effectiveContextLimit,
    roomContextLimit,
    auditScopedModelRoute,
    runtimeProviderWithFreshModels,
    assertProviderEndpoint,
    modelRouteFailoverText,
    roomRouteHandoff,
    modelRouteResetPolicy,
    roomFinalGateBlockers,
    runRoom,
    normalizeTicketExecution,
    ticketWorkOptionsWithProjectRoute,
    isTicketStarting: (ticketId: string) => ticketWorkerRuntime.isTicketStarting(ticketId),
    resolveProjectProvider,
    ensureTensorFoldStudioStylePrompt,
    streamChat,
    parseJsonLoose,
    createProjectMemoryCandidate,
    approveProjectMemoryCandidate,
    rejectProjectMemoryCandidate,
    projectMemoryCandidateDiff,
    rollbackProjectMemoryEntry,
    forgetProjectMemoryEntry,
    scopeProjectMemoryEntries,
    scopeProjectMemoryCandidates,
    registerWebhookIpc,
    webhookServer,
    rememberConnectorEvents,
    confirmSensitiveAction,
  }
}
