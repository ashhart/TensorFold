"""Deferred-eval decode: ONE lazy graph per token + on-GPU remap + cold-redo.

The next decode-hot lever on top of the fixed hot-set (``test_nemotron_runner_
fixed_hotset.py``). The synced fixed path is token-exact but still does ~one
``mx.eval`` PER MoE layer (to read routed ids for a Python residency check and a
numpy global->slot remap), serialising the GPU ~49x/token on the real 550B.

The deferred path removes every per-layer eval:

* **On-GPU remap** — instead of ``np.asarray(inds)`` + numpy gather, the gate
  wrapper returns ``local = mx.take(g2s, inds)`` LAZILY (no eval, no numpy);
  scores pass through unchanged. The native ``SwitchMLP`` then gathers ``local``
  from the prebuilt fixed stack. The whole 108-layer forward composes into ONE
  graph, evaluated once at ``lm_head``.
* **Optimistic + cold-redo** — a residency miss can't be Python-checked without a
  sync, so the gate also accumulates a LAZY cold flag (did any layer route to a
  non-resident expert?). ONE eval at end-of-token reads it alongside the argmax.
  If cold, the optimistic forward is invalid -> restore the cache snapshot and
  REDO the token via the proven-exact synced fixed path.

The hard gate is TOKEN-EXACTNESS. All-resident token: the on-GPU ``mx.take``
yields the SAME local slots the numpy remap would, so the forward is bit-
identical to the synced fixed path (already proven == stock == page). Cold token:
the optimistic forward is discarded and the token regenerated by the exact path.
So the output == stock for EVERY token, on BOTH fixtures, both branches.
"""
from __future__ import annotations

import tempfile
import unittest

from tests.fixtures.tiny_nemotron import (
    build_tiny_nemotron,
    build_tiny_nemotron_quantized,
)
from tests.test_nemotron_runner_fixed_hotset import (
    MOE_LAYERS,
    PROMPT,
    ROUTED_UNION,
    _stock_greedy,
    _stock_logits,
)


def _count_evals():
    """Patch ``mlx.core.eval`` to tally calls; returns (counter, restore).

    The deferred path's whole point is collapsing ~per-MoE-layer evals into ~1-2
    per token, so the proof is an honest call count of ``mx.eval`` itself.
    """
    import mlx.core as mx

    original = mx.eval
    counter = {"calls": 0}

    def counting(*args, **kwargs):
        counter["calls"] += 1
        return original(*args, **kwargs)

    mx.eval = counting

    def restore() -> None:
        mx.eval = original

    return counter, restore


class NemotronDeferredExactnessTests(unittest.TestCase):
    """Deferred decode == stock == synced-fixed, both fixtures, both branches."""

    def test_deferred_all_resident_logits_exact_both_fixtures(self) -> None:
        """One-shot deferred logits with a COVERING fixed set == stock == synced.

        Override the fixed set to a non-sorted superset of the routed union so
        every MoE layer is all-resident -> pure deferred (no redo). The on-GPU
        ``mx.take`` remap must reproduce the synced numpy remap bit-for-bit.
        """
        import mlx.core as mx

        from smarttensor.adapters.mlx import NemotronHStreamingForwardRunner

        cover = {layer: [7, 2, 5, 1] for layer in MOE_LAYERS}

        for builder in (build_tiny_nemotron, build_tiny_nemotron_quantized):
            with self.subTest(fixture=builder.__name__):
                with tempfile.TemporaryDirectory() as d:
                    path = builder(d)
                    stock = _stock_logits(path, PROMPT)

                    # Synced fixed path (the proven-exact reference).
                    synced = NemotronHStreamingForwardRunner(
                        str(path),
                        pin_policy="all",
                        page_experts=True,
                        fixed_hotset_experts=4,
                    )
                    self.addCleanup(synced.close)
                    synced.build_fixed_hotset(PROMPT, override=cover)
                    synced_logits = synced.forward_logits(PROMPT)
                    mx.eval(synced_logits)

                    # Deferred path.
                    deferred = NemotronHStreamingForwardRunner(
                        str(path),
                        pin_policy="all",
                        page_experts=True,
                        fixed_hotset_experts=4,
                    )
                    self.addCleanup(deferred.close)
                    deferred.build_fixed_hotset(PROMPT, override=cover)
                    got = deferred.forward_logits_deferred(PROMPT)
                    mx.eval(got)

                    self.assertEqual(tuple(got.shape), tuple(stock.shape))
                    self.assertEqual(
                        float(mx.max(mx.abs(got.astype(mx.float32) - stock.astype(mx.float32)))),
                        0.0,
                        "deferred all-resident logits diverged from stock",
                    )
                    self.assertEqual(
                        float(mx.max(mx.abs(got.astype(mx.float32) - synced_logits.astype(mx.float32)))),
                        0.0,
                        "deferred all-resident logits diverged from synced fixed",
                    )
                    # Pure deferred: no cold redo fired.
                    self.assertEqual(deferred._deferred_stats["cold_redos"], 0)
                    self.assertGreater(deferred._deferred_stats["deferred_tokens"], 0)

