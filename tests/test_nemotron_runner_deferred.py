class NemotronDeferredEvalCountTests(unittest.TestCase):
    """The deferred all-resident path does FAR fewer evals than the synced path."""

    def test_deferred_does_far_fewer_evals_per_token(self) -> None:
        """Per decode token: deferred ~1-2 evals; synced ~one PER MoE layer.

        The toy has 2 MoE layers, so the synced fixed path evals at least twice
        per token (one ``mx.eval(inds)`` per MoE layer) plus the argmax. The
        deferred path must collapse to a small constant (target ~1-2): no
        per-layer eval at all.
        """
        from smarttensor.adapters.mlx import NemotronHStreamingForwardRunner

        steps = 6
        cover = {layer: [7, 2, 5, 1] for layer in MOE_LAYERS}
        with tempfile.TemporaryDirectory() as d:
            path = build_tiny_nemotron(d)

            # --- Synced fixed path eval count (one decode token).
            synced = NemotronHStreamingForwardRunner(
                str(path),
                pin_policy="all",
                page_experts=True,
                fixed_hotset_experts=4,
            )
            self.addCleanup(synced.close)
            synced.build_fixed_hotset(PROMPT, override=cover)
            # Warm prefill OUTSIDE the counter (we measure steady-state decode).
            synced.generate_greedy(PROMPT, 1)
            counter, restore = _count_evals()
            try:
                synced._decode_one_token_synced(PROMPT)
            finally:
                restore()
            synced_evals = counter["calls"]

            # --- Deferred path eval count (one decode token).
            deferred = NemotronHStreamingForwardRunner(
                str(path),
                pin_policy="all",
                page_experts=True,
                fixed_hotset_experts=4,
            )
            self.addCleanup(deferred.close)
            deferred.build_fixed_hotset(PROMPT, override=cover)
            deferred.generate_greedy_deferred(PROMPT, 1)
            counter, restore = _count_evals()
            try:
                deferred._decode_one_token_deferred(PROMPT)
            finally:
                restore()
            deferred_evals = counter["calls"]

            # The synced path pays at least one eval per MoE layer (2 here).
            self.assertGreaterEqual(
                synced_evals,
                len(MOE_LAYERS),
                "synced fixed path should eval at least once per MoE layer",
            )
            # The deferred path collapses to a small constant, strictly fewer than
            # the synced per-layer cost (and bounded by ~1-2: the single end-of-
            # token flag+argmax eval).
            self.assertLess(
                deferred_evals,
                synced_evals,
                f"deferred ({deferred_evals}) not fewer than synced ({synced_evals})",
            )
            self.assertLessEqual(
                deferred_evals,
                2,
                f"deferred path did {deferred_evals} evals (target ~1-2)",
            )


class NemotronDeferredDefaultPathTests(unittest.TestCase):
    """The deferred path is fully opt-in; default decode is untouched."""

    def test_frequency_built_deferred_is_exact(self) -> None:
        """A frequency-built (no override) deferred decode is exact and pure-deferred."""
        from smarttensor.adapters.mlx import NemotronHStreamingForwardRunner

        steps = 8
        with tempfile.TemporaryDirectory() as d:
            path = build_tiny_nemotron_quantized(d)
            stock = _stock_greedy(path, PROMPT, steps)

            deferred = NemotronHStreamingForwardRunner(
                str(path),
                pin_policy="all",
                page_experts=True,
                fixed_hotset_experts=3,  # == |{2,5,7}|, covers the union
            )
            self.addCleanup(deferred.close)
            built = deferred.build_fixed_hotset(PROMPT, warmup_tokens=8)
            for layer in MOE_LAYERS:
                self.assertEqual(set(built[layer]["order"]), ROUTED_UNION)

            out = deferred.generate_greedy_deferred(PROMPT, steps)
            self.assertEqual(
                out["tokens"], stock, "frequency-built deferred decode diverged from stock"
            )
            self.assertEqual(out["cold_redos"], 0)

    def test_deferred_requires_fixed_hotset(self) -> None:
        """``generate_greedy_deferred`` without a built hot-set raises (opt-in)."""
        from smarttensor.adapters.mlx import NemotronHStreamingForwardRunner

        with tempfile.TemporaryDirectory() as d:
            path = build_tiny_nemotron(d)
            runner = NemotronHStreamingForwardRunner(
                str(path), pin_policy="all", page_experts=True
            )
            self.addCleanup(runner.close)
            with self.assertRaises(Exception):
                runner.generate_greedy_deferred(PROMPT, 4)


