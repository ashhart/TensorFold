    instruct_sampling: ?[]const u8 = null, // none, card or name=value pairs: thinking-off sampled chats' set
    thinking: bool = true,
    reasoning_effort: ?[]const u8 = null,
    thinking_budget: i64 = 0,
    thinking_reserve: i64 = 0,
    loop_guard: bool = false,
