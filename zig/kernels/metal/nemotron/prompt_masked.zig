//! Separate exceptional prompt libraries; the finite contiguous and paged source strings are unchanged.
const std = @import("std");
const paged = @import("paged.zig");
pub const original = @embedFile("../prefill/attention_nax.metal");
const helpers = @embedFile("prompt_masked.h");
const picker = @embedFile("prompt_pick.metal");
pub const tags = paged.prefill_tags;

fn edit(comptime text: []const u8, comptime from: []const u8, comptime to: []const u8, comptime count: usize) []const u8 {
    @setEvalBranchQuota(20_000_000);
    if (std.mem.count(u8, text, from) != count) @compileError("Nemotron masked prompt: source edit no longer matches");
    var out: []const u8 = "";
    var rest = text;
    while (std.mem.indexOf(u8, rest, from)) |i| {
        out = out ++ rest[0..i] ++ to;
        rest = rest[i + from.len ..];
    }
    return out ++ rest;
}

fn body(comptime text: []const u8) []const u8 {
    @setEvalBranchQuota(20_000_000);
    const begin = std.mem.indexOf(u8, text, "// One 64-query block").?;
    const end = std.mem.indexOfPos(u8, text, begin, "}  // namespace tfp").?;
    return edit(text[begin..end], "attention_pv(acc[d], acc[d + 1], s[k], v0, v1, ushort(lane));",
        "if (CAUSAL && kb >= first_masked)\n" ++
        "          nemo_masked_pv(acc[d], acc[d + 1], s[k], v0, v1, ushort(lane), home, kb * BK + 16 * k, P[3], int(tg.x) * BQ + P[11] + tm + home.y);\n" ++
        "        else attention_pv(acc[d], acc[d + 1], s[k], v0, v1, ushort(lane));", 1);
}

/// All four alignments of the exceptional contiguous operator, retaining the original file as its prefix.
pub const contiguous = blk: {
    const before = "// ---- entry points: generated by tools/zig/check_prefill_ops.py --write ----";
    const at = std.mem.indexOf(u8, original, before).?;
    const b = edit(body(original), "inline void attention_nax(", "inline void attention_masked(", 1);
    var entries = edit(original[at..], "custom_kernel_tf_attention_nax_bf16_", "nemotron_attention_masked_", 4);
    entries = edit(entries, "tfp::attention_nax<", "tfp::attention_masked<", 4);
    break :blk original ++ helpers ++ "namespace tfp {\n" ++ b ++ "}\n" ++ entries ++ picker;
};

/// The same correction after the paged twin's existing address rewrite; its finite source is also retained.
pub const paged_source = blk: {
    @setEvalBranchQuota(20_000_000);
    const start = std.mem.indexOf(u8, paged.prefill, "inline void attention_nax_paged(").?;
    const template_start = std.mem.lastIndexOf(u8, paged.prefill[0..start], "// One 64-query block").?;
    const b = edit(body(paged.prefill[template_start..]), "inline void attention_nax_paged(", "inline void attention_masked_paged(", 1);
    const entries_at = std.mem.indexOfPos(u8, paged.prefill, start, "[[max_total_threads_per_threadgroup(128)]]").?;
    var entries = edit(paged.prefill[entries_at..], "nemotron_attention_paged_", "nemotron_attention_masked_paged_", 4);
    entries = edit(entries, "tfp::attention_nax_paged<", "tfp::attention_masked_paged<", 4);
    var scan = edit(picker, "nemotron_prompt_scan(", "nemotron_prompt_scan_paged(", 1);
    scan = edit(scan, "device atomic_uint* flag [[buffer(2)]], uint3 tg", "device atomic_uint* flag [[buffer(2)]], device const uint* table [[buffer(3)]], constant ulong& page_bytes [[buffer(4)]], uint3 tg", 1);
    scan = edit(scan, "  const device bfloat* v = V + long(tg.z) * P[19];\n", "", 1);
    scan = edit(scan, "    const uint2 bits = *(const device uint2*)(v + long(key) * P[20] + lane * 4);", "    const device bfloat* v = (const device bfloat*)((const device uchar*)V + nemo_paged_row(table, uint(key), page_bytes, tg.z, uint(P[20])));\n    const uint2 bits = *(const device uint2*)(v + lane * 4);", 1);
    break :blk paged.prefill ++ helpers ++ "namespace tfp {\n" ++ b ++ "}\n" ++ entries ++ scan;
};

pub fn name(comptime is_paged: bool, comptime index: usize) [:0]const u8 {
    return "nemotron_attention_masked_" ++ (if (is_paged) "paged_" else "") ++ tags[index] ++
        (if (is_paged) "" else "_t_bfloat16_t_bfloat16_t_bfloat16_t_int32_t_float_bfloat16_t");
}

test "the finite attention libraries remain the original source, with exceptional kernels in separate libraries" {
    try std.testing.expect(std.mem.startsWith(u8, contiguous, original));
    try std.testing.expect(std.mem.startsWith(u8, paged_source, paged.prefill));
    inline for (0..4) |i| {
        try std.testing.expect(std.mem.indexOf(u8, contiguous, name(false, i)) != null);
        try std.testing.expect(std.mem.indexOf(u8, paged_source, name(true, i)) != null);
    }
}
