#!/usr/bin/env python3
"""The device code of the Python GLM-5.3-Flash engine's own CUDA extension (families/glm5_next/cuda/kda.cu) as a
zig/kernels/cuda/glm copy: Flash Next's gen_copies.py rules (the source up to its first ATen-using function, ATen
includes dropped, the anonymous namespace kept) plus explicit instantiations of every template kernel the Python
build instantiated (demangled from its cubin). The grouped experts and the 4-bit matmuls are the shared extensions
Flash Next's copies already hold (the same symbols).
usage: gen_copies.py <tensorfold src dir (the patched python engine)> <symbols.json of the Python cubins> <out dir>"""
import json, sys
from pathlib import Path

fn: dict = {}
text_fn = (Path(__file__).parent.parent / "flashnext" / "gen_copies.py").read_text().replace("sys.exit(main())", "")
exec(compile(text_fn, "flashnext/gen_copies.py", "exec"), fn)      # its rules, without running its main
src, syms, out = Path(sys.argv[1]), json.loads(Path(sys.argv[2]).read_text()), Path(sys.argv[3])
out.mkdir(parents=True, exist_ok=True)
rel = "families/glm5_next/cuda/kda.cu"
body = fn["device_part"]((src / rel).read_text())
kda = [s for k, v in syms.items() if "glm_kda" in k for s in v]
inst = fn["instantiations"](kda)
head = f"// Device code of src/tensorfold/{rel} (generated by zig/tests/cuda/glm/gen_copies.py; do not edit).\n"
text = head + body + ("\n// the Python build's instantiations\nnamespace {\n" + "\n".join(inst) + "\n}  // namespace\n"
                      if inst else "")
(out / "kda.cu").write_text(text)
print(f"kda.cu: {len(inst)} instantiations")
