//! Pure CUDA kernel-definition and dependency-prologue scanning; no manual kernel allowlist.
const std = @import("std");

/// One defined (not merely declared or instantiated) kernel and its body's normalized opening.
pub const Definition = struct { name: []const u8, opening: []const u8 };

const open_c = "/" ++ "*";
const close_c = "*" ++ "/";

fn ident(c: u8) bool {
    return std.ascii.isAlphanumeric(c) or c == '_' or c == '#';
}

/// The index past a comment or a string or character literal starting at `k`, or null when none starts there.
fn skip(s: []const u8, k: usize) ?usize {
    const rest = s[k..];
    if (std.mem.startsWith(u8, rest, "//")) return std.mem.indexOfScalarPos(u8, s, k, '\n') orelse s.len;
    if (std.mem.startsWith(u8, rest, open_c)) return if (std.mem.indexOfPos(u8, s, k + 2, close_c)) |e| e + 2 else s.len;
    if (rest.len > 0 and (rest[0] == '"' or rest[0] == '\'')) {
        var e = k + 1;
        while (e < s.len and s[e] != rest[0]) e += if (s[e] == '\\') 2 else 1;
        return @min(e + 1, s.len);
    }
    return null;
}

/// The index of the bracket closing the one at `i` (comments and literals skipped), or null when unbalanced.
fn close(s: []const u8, i: usize, open: u8, shut: u8) ?usize {
    var depth: usize = 0;
    var k = i;
    while (k < s.len) {
        if (skip(s, k)) |next| {
            k = next;
            continue;
        }
        if (s[k] == open) depth += 1 else if (s[k] == shut) {
            depth -= 1;
            if (depth == 0) return k;
        }
        k += 1;
    }
    return null;
}

/// A body's text with macro line breaks, line comments and leading space dropped.
fn opening(a: std.mem.Allocator, body: []const u8) ![]const u8 {
    var out: std.ArrayList(u8) = .empty;
    var k: usize = 0;
    while (k < body.len) {
        if (body[k] == '\\' and k + 1 < body.len and body[k + 1] == '\n') {
            k += 2;
        } else if (body[k] == '/' and k + 1 < body.len and body[k + 1] == '/') {
            while (k < body.len and body[k] != '\n') k += 1;
        } else {
            try out.append(a, body[k]);
            k += 1;
        }
    }
    return std.mem.trimStart(u8, out.items, " \t\r\n");
}

/// Every global-kernel definition in `src`, including definitions generated by macros.
pub fn definitions(a: std.mem.Allocator, src: []const u8, out: *std.ArrayList(Definition)) !void {
    var at: usize = 0;
    while (std.mem.indexOfPos(u8, src, at, "__global__")) |g| {
        at = g + "__global__".len;
        const line = src[(if (std.mem.lastIndexOfScalar(u8, src[0..g], '\n')) |n| n + 1 else 0)..g];
        if (std.mem.indexOf(u8, line, "//") != null) continue;
        var i = at;
        var name: []const u8 = "";
        while (i < src.len and src[i] != '(') {
            if (ident(src[i])) {
                const start = i;
                while (i < src.len and ident(src[i])) i += 1;
                const tok = src[start..i];
                if (std.mem.eql(u8, tok, "__launch_bounds__")) {
                    const p = std.mem.indexOfScalarPos(u8, src, i, '(') orelse return error.Unparsed;
                    i = (close(src, p, '(', ')') orelse return error.Unparsed) + 1;
                } else name = tok;
            } else if (src[i] == '<') {
                i = (close(src, i, '<', '>') orelse return error.Unparsed) + 1;
            } else i += 1;
        }
        const params_end = close(src, i, '(', ')') orelse return error.Unparsed;
        var k = params_end + 1;
        while (k < src.len and src[k] != '{' and src[k] != ';') k = skip(src, k) orelse k + 1;
        if (k >= src.len or src[k] == ';') continue;
        const end = close(src, k, '{', '}') orelse return error.Unparsed;
        try out.append(a, .{ .name = name, .opening = try opening(a, src[k + 1 .. end]) });
    }
}

/// The positive table: every definition whose first body statement is exactly `prologue`.
pub fn prologues(a: std.mem.Allocator, src: []const u8, prologue: []const u8, out: *std.ArrayList([]const u8)) !void {
    var found: std.ArrayList(Definition) = .empty;
    try definitions(a, src, &found);
    for (found.items) |d| if (std.mem.startsWith(u8, d.opening, prologue)) try out.append(a, d.name);
}

pub fn contains(table: []const []const u8, name: []const u8) bool {
    for (table) |candidate| if (std.mem.eql(u8, candidate, name)) return true;
    return false;
}

test "a positive prologue table comes from definitions, including macro bodies" {
    var arena: std.heap.ArenaAllocator = .init(std.testing.allocator);
    defer arena.deinit();
    const source =
        "#define K(NAME) \\\n" ++
        "extern \"C\" __global__ void NAME(int* x) { qwen_pdl::enter(); \\\n" ++
        "  x[0] = 1; \\\n" ++
        "}\n" ++
        "extern \"C\" __global__ void absent(int* x) { x[0] = 1; }\n";
    var table: std.ArrayList([]const u8) = .empty;
    try prologues(arena.allocator(), source, "qwen_pdl::enter();", &table);
    try std.testing.expectEqual(@as(usize, 1), table.items.len);
    try std.testing.expect(contains(table.items, "NAME"));
    try std.testing.expect(!contains(table.items, "absent"));
}
